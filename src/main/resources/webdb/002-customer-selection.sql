CREATE TABLE WEB_CUSTOMER_SELECTION (
    Reference TEXT NOT NULL PRIMARY KEY,
    MaSuat INTEGER NOT NULL,
    MaPhim TEXT NOT NULL,
    MaPhong TEXT NOT NULL,
    ShowStart TEXT NOT NULL,
    ExpiresAt TEXT NOT NULL,
    MaGiaoDich TEXT UNIQUE REFERENCES GIAODICH
);

CREATE TABLE WEB_CUSTOMER_SELECTION_SEAT (
    Reference TEXT NOT NULL REFERENCES WEB_CUSTOMER_SELECTION ON DELETE CASCADE,
    MaGhe INTEGER NOT NULL,
    Cho TEXT NOT NULL,
    TenLoaiGhe TEXT NOT NULL,
    GiaVe INTEGER NOT NULL CHECK (GiaVe > 0),
    PRIMARY KEY (Reference, MaGhe)
);

CREATE INDEX WEB_CUSTOMER_SELECTION_OPEN_EXPIRY ON WEB_CUSTOMER_SELECTION (ExpiresAt)
WHERE MaGiaoDich IS NULL;
